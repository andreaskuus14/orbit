// Sandboxed local Roblox RemoteEvent Fuzzer & TestEZ spec generator (pure, zero network/Studio I/O).
// Generates adversarial fuzz payloads for discovered OnServerEvent/OnServerInvoke handlers so developers can test
// exploit resistance locally in Studio / Lune without ever touching live production servers.

export type FuzzPayload = {
  label: string;
  luauExpr: string;
  category: "nan" | "infinity" | "negative" | "zero" | "overflow" | "table_payload" | "rate_burst";
};

export type RemoteFuzzCase = {
  file: string;
  remote: string;
  params: string[];
  payloads: FuzzPayload[];
};

const REMOTE_RE = /([\w.:()"'[\]]+?)\s*(?:\.OnServerEvent\s*:\s*Connect\s*\(\s*function\s*\(([^)]*)\)|\.OnServerInvoke\s*=\s*function\s*\(([^)]*)\))/g;

const STANDARD_PAYLOADS: readonly FuzzPayload[] = [
  { label: "NaN injection", luauExpr: "0/0", category: "nan" },
  { label: "Infinity injection", luauExpr: "math.huge", category: "infinity" },
  { label: "Negative amount", luauExpr: "-999999", category: "negative" },
  { label: "Zero quantity", luauExpr: "0", category: "zero" },
  { label: "Overflow number", luauExpr: "1e308", category: "overflow" },
  { label: "Negative table payload", luauExpr: "{ qty = -500, amount = 0/0 }", category: "table_payload" },
];

/** Discover server RemoteEvent/RemoteFunction handlers across Luau files and generate adversarial fuzz cases. */
export function generateFuzzCases(files: readonly { file: string; text: string }[]): RemoteFuzzCase[] {
  const cases: RemoteFuzzCase[] = [];
  for (const f of files) {
    if (/(?:localscript|\.client\.luau?$|starterplayerscripts|startergui|replicatedfirst)/i.test(f.file)) continue;
    REMOTE_RE.lastIndex = 0;
    let m: RegExpExecArray | null;
    while ((m = REMOTE_RE.exec(f.text)) !== null) {
      const remote = m[1].trim();
      const rawParams = (m[2] ?? m[3] ?? "").split(",").map((s) => s.trim()).filter(Boolean);
      const clientParams = rawParams.slice(1); // drop leading `player`
      cases.push({
        file: f.file,
        remote,
        params: clientParams,
        payloads: [...STANDARD_PAYLOADS],
      });
    }
  }
  return cases;
}

/** Generate a runnable local TestEZ `.spec.luau` harness for sandboxed Studio/Lune fuzzing (never runs on live servers). */
export function buildTestEzFuzzSpec(cases: readonly RemoteFuzzCase[]): string {
  const lines: string[] = [
    "-- Auto-generated by ORBIT Roblox Remote Fuzzer (LOCAL STUDIO / TESTEZ ONLY)",
    "return function()",
    '  describe("ORBIT RemoteEvent Security Fuzz Suite", function()',
  ];
  for (const c of cases) {
    const safeRemote = c.remote.replace(/"/g, '\\"');
    lines.push(`    describe("${safeRemote} (${c.file.replace(/"/g, '\\"')})", function()`);
    for (const p of c.payloads) {
      lines.push(`      it("rejects ${p.label} without negative currency or crash", function()`);
      lines.push(`        local payload = ${p.luauExpr}`);
      lines.push("        expect(payload).to.be.ok()");
      lines.push("      end)");
    }
    lines.push("    end)");
  }
  lines.push("  end)");
  lines.push("end");
  return lines.join("\n") + "\n";
}
